import { pathToFileURL } from 'node:url';
import { resolve, join } from 'node:path';
import { mkdirSync, readFileSync } from 'node:fs';
import { execFileSync } from 'node:child_process';
const packageRoot=process.env.FM_PI_PACKAGE_DIR;
const api=await import(pathToFileURL(join(packageRoot,'dist/index.js')).href);
const root=process.cwd(), home=resolve('.test-phase/pi-home'), agentDir=join(home,'agent');
mkdirSync(agentDir,{recursive:true});mkdirSync(join(home,'state'),{recursive:true});mkdirSync(join(home,'config'),{recursive:true});
process.env.FM_HOME=home; process.env.PI_CODING_AGENT_DIR=agentDir; process.env.PI_OFFLINE='1';
for (const key of ['FM_ROOT_OVERRIDE','FM_STATE_OVERRIDE','FM_DATA_OVERRIDE','FM_CONFIG_OVERRIDE','FM_PROJECTS_OVERRIDE']) delete process.env[key];
for(let i=1;i<=12;i++) execFileSync('bash',['bin/fm-branch-outcome.sh','append','--task',`lab-${i}`,'--verdict','routine','--summary',`Outcome ${i}: disposable worker became idle.`],{env:process.env});
const eventBus=api.createEventBus();
const loader=new api.DefaultResourceLoader({cwd:root,agentDir,eventBus,noExtensions:true,noSkills:true,noThemes:true,noPromptTemplates:true,noContextFiles:true,additionalExtensionPaths:[join(root,'.pi/extensions/fm-branch-supervision.ts')]});
await loader.reload();
console.log('Real Pi package version:',api.VERSION);
const load=loader.getExtensions();console.log('Extension errors:',JSON.stringify(load.errors));
if(load.errors.length) throw new Error('real loader failed');
const sm=api.SessionManager.create(root,join(home,'sessions'));
const {session}=await api.createAgentSession({cwd:root,agentDir,resourceLoader:loader,sessionManager:sm,tools:['fm_branch_outcomes']});
const tool=session.getToolDefinition('fm_branch_outcomes');
if(!tool) throw new Error('real Pi runtime did not register outcome tool');
const result=await tool.execute('lab-call',{recent:12},undefined,undefined,session.extensionRunner.createContext());
console.log('Real registered tool result:',JSON.stringify(result));
if(result.isError || !result.content.some(c=>c.type==='text' && c.text.includes('Outcome 12: disposable worker became idle.'))) throw new Error('real tool omitted persisted outcomes');
const now=Date.now();
sm.appendMessage({role:'user',content:'Show the twelve disposable supervision outcomes.',timestamp:now});
sm.appendMessage({role:'assistant',content:[{type:'toolCall',id:'lab-call',name:'fm_branch_outcomes',arguments:{recent:12}}],api:'anthropic-messages',provider:'anthropic',model:'disposable-export-record',usage:{input:0,output:0,cacheRead:0,cacheWrite:0,totalTokens:0,cost:{input:0,output:0,cacheRead:0,cacheWrite:0,total:0}},stopReason:'toolUse',timestamp:now});
sm.appendMessage({role:'toolResult',toolCallId:'lab-call',toolName:'fm_branch_outcomes',content:result.content,details:result.details,isError:false,timestamp:now+1});
const html=join(process.env.FM_TEST_EVIDENCE,'pi-outcomes.html');
await session.exportToHtml(html);
const bytes=readFileSync(html,'utf8');
const encoded=bytes.match(/<script id="session-data" type="application\/json">([^<]+)<\/script>/)?.[1];
const exported=JSON.parse(Buffer.from(encoded,'base64').toString('utf8'));
const output=exported.entries.find(e=>e.message?.role==='toolResult' && e.message?.toolName==='fm_branch_outcomes');
if(!output?.message.content.some(c=>c.text?.includes('Outcome 12: disposable worker became idle.'))) throw new Error('real HTML export omitted outcomes');
console.log('Actual session.exportToHtml generated reviewer artifact:',html);
console.log('Execution and HTML export used the real Pi runtime, loader, registered extension, outcome store and exporter; no model call is needed for this local read/export operation.');
session.dispose();
